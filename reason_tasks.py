#!/usr/bin/env python3
"""reason_tasks.py -- procedurally generated reasoning / memory tasks with ground truth, for small models.

Why: perplexity cannot tell "stores facts" from "computes". These tasks isolate specific abilities, are generated by
code (so nothing can be memorised from web text), and give an accuracy-vs-difficulty curve with held-out difficulties.

TASKS (answer-only loss; metric = INSTANCE-EXACT accuracy, i.e. every answer token right; under teacher forcing this is
identical to greedy generation reproducing the answer)
  mqar   in-context recall.   <bos> k1 v1 ... kn vn <q> kq <a> vq                 difficulty = n pairs
  hop    multi-hop chasing.   <bos> a1 b1 ... a12 b12 <q> s <hop>*k <a> node      difficulty = k hops (needs depth)
         (edges a->b form ONE random 12-cycle; answer = k-th successor of s, never s itself for k<12)
  add    little-endian digit addition.  <bos> A + B <a> S                          difficulty = digits d
  state  running sum mod 5 over n digits (state tracking). <bos> x1..xn <a> s      difficulty = n
  facts  facts stored IN THE WEIGHTS.  <bos> <q> 3 letters <a> 3 digits            N fixed random facts, no context

RIGOR (all enforced + checked by `python reason_tasks.py --selftest`)
  * Disjoint splits by CONTENT HASH: bucket(instance tokens) % 20 -> 0 = test, 1 = val (LR tuning), >=2 = train.
    A test instance can never be generated in training, however small the instance space is.
    (`facts` is the exception by design: recall of the training facts IS the task.)
  * Held-out DIFFICULTY: every task has test difficulties the training stream never contains (marked OOD).
  * Eval sets are deterministic and independent of the training seed: every model sees exactly the same instances.
    Instances are de-duplicated; if the space is too small to reach n, the real n is reported (and used for CIs).
  * Training batches are a pure function of (seed, step): exact resume, identical data for every model at a seed.
  * Trivial-baseline table (best constant answer + task-specific shortcut heuristics) so "above chance" is
    measured against what a cheater could get, not just 1/vocab.
  * Independent verifier re-derives each answer from the tokens alone (does not share code with the generators).
"""
import argparse
import hashlib
import random
from array import array
from collections import Counter

import numpy as np

# ------------------------------------------------------------------------------------------------ vocabulary
N_KEY, N_VAL, N_NODE = 64, 64, 32
_names = ["<pad>", "<bos>", "<q>", "<a>", "<hop>", "+"]
_names += [str(i) for i in range(10)]
_names += [f"k{i}" for i in range(N_KEY)] + [f"v{i}" for i in range(N_VAL)] + [f"n{i}" for i in range(N_NODE)]
_names += [chr(97 + i) for i in range(26)]
TOK = {n: i for i, n in enumerate(_names)}
ITOK = _names
PAD, BOS, Q, A, HOP, PLUS = (TOK[s] for s in ["<pad>", "<bos>", "<q>", "<a>", "<hop>", "+"])
DIG0, KEY0, VAL0, NODE0, LET0 = TOK["0"], TOK["k0"], TOK["v0"], TOK["n0"], TOK["a"]
VOCAB_MIN = len(_names)                                   # ids actually used (the model vocab is padded above this)
N_HOP_NODES = 12
STATE_MOD = 5
FACT_KEY_LEN, FACT_VAL_LEN = 3, 3
FACT_SEED = 0                                             # the fact table is the same for every model and seed
N_BUCKETS = 20                                            # bucket 0 = test, 1 = val, rest = train
EVAL_SEED = 777


# ------------------------------------------------------------------------------------------------ generators
# Each returns (tokens, mask); mask[i] = 1 where tokens[i] is an ANSWER token the model must predict.
def gen_mqar(rng, n):
    ks = rng.sample(range(N_KEY), n)
    vs = [rng.randrange(N_VAL) for _ in range(n)]
    qi = rng.randrange(n)
    t = [BOS]
    for k, v in zip(ks, vs):
        t += [KEY0 + k, VAL0 + v]
    t += [Q, KEY0 + ks[qi], A, VAL0 + vs[qi]]
    return t, [0] * (len(t) - 1) + [1]


def gen_hop(rng, k):
    nodes = rng.sample(range(N_NODE), N_HOP_NODES)          # one random 12-cycle: the answer is never the start node
    tgt = nodes[1:] + nodes[:1]
    nxt = dict(zip(nodes, tgt))
    edges = list(nxt.items())
    rng.shuffle(edges)
    s = rng.choice(nodes)
    cur = s
    for _ in range(k):
        cur = nxt[cur]
    t = [BOS]
    for a, b in edges:
        t += [NODE0 + a, NODE0 + b]
    t += [Q, NODE0 + s] + [HOP] * k + [A, NODE0 + cur]
    return t, [0] * (len(t) - 1) + [1]


def _digits_le(x, n):
    return [(x // 10 ** i) % 10 for i in range(n)]


def gen_add(rng, d):
    a, b = rng.randrange(10 ** d), rng.randrange(10 ** d)
    ans = [DIG0 + x for x in _digits_le(a + b, d + 1)]
    t = [BOS] + [DIG0 + x for x in _digits_le(a, d)] + [PLUS] + [DIG0 + x for x in _digits_le(b, d)] + [A] + ans
    return t, [0] * (len(t) - len(ans)) + [1] * len(ans)


def gen_state(rng, n):
    xs = [rng.randrange(STATE_MOD) for _ in range(n)]
    t = [BOS] + [DIG0 + x for x in xs] + [A, DIG0 + sum(xs) % STATE_MOD]
    return t, [0] * (len(t) - 1) + [1]


def make_fact_table(n, seed=FACT_SEED):
    """n distinct 3-letter keys -> random 3-digit values.  -> list of (key_tokens, value_tokens)"""
    rng = random.Random(seed)
    assert n <= 26 ** FACT_KEY_LEN
    out = []
    for kid in rng.sample(range(26 ** FACT_KEY_LEN), n):
        key = [LET0 + (kid // 26 ** i) % 26 for i in range(FACT_KEY_LEN)]
        val = [DIG0 + rng.randrange(10) for _ in range(FACT_VAL_LEN)]
        out.append((key, val))
    return out


def gen_fact(table, idx):
    key, val = table[idx]
    t = [BOS, Q] + key + [A] + val
    return t, [0] * (len(t) - len(val)) + [1] * len(val)


# task -> train difficulties (training stream draws uniformly from these) and test difficulties.
# test difficulties not in `train` are OOD (never seen in training).
TASKS = {
    "mqar":  dict(gen=gen_mqar,  train=[2, 3, 4, 6, 8, 12, 16, 24], test=[2, 4, 8, 16, 24, 32, 48, 64]),
    "hop":   dict(gen=gen_hop,   train=[1, 2, 3, 4, 5, 6],          test=[1, 2, 3, 4, 5, 6, 7, 8, 10]),
    "add":   dict(gen=gen_add,   train=[1, 2, 3, 4, 5, 6],          test=[1, 2, 3, 4, 5, 6, 8, 10]),
    "state": dict(gen=gen_state, train=[2, 4, 8, 12, 16, 24],       test=[2, 4, 8, 12, 16, 24, 32, 48]),
    "facts": dict(gen=None,      train=[0],                         test=[0]),
}
REASONING = ["mqar", "hop", "add", "state"]               # `facts` is a storage task, reported separately
DEFAULT_MIX = dict(mqar=0.2, hop=0.2, add=0.2, state=0.2, facts=0.2, induct=0.0)


def gen_induct(rng, L):
    """AUXILIARY, train-only (never evaluated, no verifier): a random token string, a separator, then the same string again.
    Loss on the second copy (except its first token).  Dense signal that teaches the 'find the earlier occurrence, copy what
    followed it' circuit (induction) that mqar and hop need.  Tokens come from the key/value/node pools."""
    pool = list(range(KEY0, VAL0 + N_VAL)) + list(range(NODE0, NODE0 + N_NODE))
    sq = [rng.choice(pool) for _ in range(L)]
    t = [BOS] + sq + [A] + sq
    return t, [0] * (L + 3) + [1] * (L - 1)


AUX_TASKS = {"induct": dict(gen=gen_induct, train=[6, 8, 12, 16, 24, 32])}


def is_ood(task, diff):
    return diff not in TASKS[task]["train"]


def max_len():
    """longest instance any split can produce (the model's ctx must be >= max_len-1)"""
    return max(len(TASKS["mqar"]["gen"](random.Random(0), TASKS["mqar"]["test"][-1])[0]),
               len(TASKS["hop"]["gen"](random.Random(0), TASKS["hop"]["test"][-1])[0]),
               len(TASKS["add"]["gen"](random.Random(0), TASKS["add"]["test"][-1])[0]),
               len(TASKS["state"]["gen"](random.Random(0), TASKS["state"]["test"][-1])[0]))


# ------------------------------------------------------------------------------------------------ splits
def bucket(tokens):
    h = hashlib.blake2b(array("H", tokens).tobytes(), digest_size=4).digest()
    return int.from_bytes(h, "little") % N_BUCKETS


def make_instance(task, diff, rng, facts=None, banned=None):
    """-> (tokens, mask, bucket) ; bucket is None for `facts`"""
    if task == "facts":
        while True:
            i = rng.randrange(len(facts))
            if banned is None or i not in banned:
                break
        if banned is not None:
            banned.add(i)
        t, m = gen_fact(facts, i)
        return t, m, None
    t, m = TASKS[task]["gen"](rng, diff)
    return t, m, bucket(t)


# ------------------------------------------------------------------------------------------------ training stream
def make_batch(seed, step, batch, seq, facts, mix=None, frac=1.0):
    """Pure function of (seed, step, ...).  -> x (B,seq) long, y (B,seq) long, m (B,seq) float answer-token mask.
    Instances are packed into rows (never split across rows), rows padded with <pad>.  A `facts` key is never
    repeated inside one row, so a fact cannot be answered by copying it from earlier in the same row."""
    mix = mix or DEFAULT_MIX
    names = [n for n in mix if mix[n] > 0 and (n != "facts" or facts)]
    probs = [mix[n] for n in names]
    rng = random.Random(seed * 1_000_003 + step)
    X = np.full((batch, seq + 1), PAD, dtype=np.int64)
    M = np.zeros((batch, seq + 1), dtype=np.float32)
    for r in range(batch):
        pos, used, fails = 0, set(), 0
        while fails < 8:
            task = rng.choices(names, probs)[0]
            if task in AUX_TASKS:
                t, m = AUX_TASKS[task]["gen"](rng, rng.choice(AUX_TASKS[task]["train"]))
                if pos + len(t) > seq + 1:
                    fails += 1
                    continue
                X[r, pos:pos + len(t)] = t
                M[r, pos:pos + len(t)] = m
                pos += len(t)
                continue
            dl = TASKS[task]["train"]
            if frac < 1.0:                                    # curriculum: only the easiest ceil(frac*len) train difficulties
                dl = dl[:max(2, -(-int(frac * 1000) * len(dl) // 1000))]
            diff = rng.choice(dl)
            while True:
                t, m, b = make_instance(task, diff, rng, facts, used)
                if b is None or b >= 2:                   # train buckets only
                    break
            if pos + len(t) > seq + 1:
                fails += 1
                continue
            X[r, pos:pos + len(t)] = t
            M[r, pos:pos + len(t)] = m
            pos += len(t)
    x, y, m = X[:, :-1], X[:, 1:], M[:, 1:]               # m[i] marks target y[i] (= token i+1) as an answer token
    return x.copy(), y.copy(), m.copy()


# ------------------------------------------------------------------------------------------------ eval sets
def build_eval(split, n_per=500, facts=None, max_tries_mult=100):
    """-> {(task, diff): [(tokens, mask), ...]} deterministic, de-duplicated, disjoint from training (hash bucket)."""
    want = {"test": 0, "val": 1}[split]
    out = {}
    for task, spec in TASKS.items():
        for diff in spec["test"]:
            if task == "facts":
                if not facts:
                    continue
                idx = random.Random(f"{split}-facts-{EVAL_SEED}").sample(range(len(facts)), min(n_per, len(facts)))
                out[(task, diff)] = [gen_fact(facts, i) for i in idx]
                continue
            rng = random.Random(f"{split}-{task}-{diff}-{EVAL_SEED}")
            seen, items = set(), []
            for _ in range(n_per * max_tries_mult):
                t, m, b = make_instance(task, diff, rng)
                if b != want:
                    continue
                key = tuple(t)
                if key in seen:
                    continue
                seen.add(key)
                items.append((t, m))
                if len(items) >= n_per:
                    break
            out[(task, diff)] = items
    return out


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 1.0)
    p = k / n
    den = 1 + z * z / n
    c = (p + z * z / (2 * n)) / den
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / den
    return (max(0.0, c - h), min(1.0, c + h))


# ------------------------------------------------------------------------------------------------ independent verifier
def solve_from_tokens(task, toks, facts=None):
    """Re-derive the answer tokens from the PROMPT alone (tokens before the first answer token). Own parsing code."""
    ia = len(toks) - 1
    if task == "mqar":
        a_pos = toks.index(A)
        q = toks[a_pos - 1]
        body = toks[1:toks.index(Q)]
        d = {body[i]: body[i + 1] for i in range(0, len(body), 2)}
        return [d[q]]
    if task == "hop":
        qpos = toks.index(Q)
        body = toks[1:qpos]
        nxt = {body[i]: body[i + 1] for i in range(0, len(body), 2)}
        s = toks[qpos + 1]
        k = toks[qpos + 2:toks.index(A)].count(HOP)
        for _ in range(k):
            s = nxt[s]
        return [s]
    if task == "add":
        a_pos = toks.index(A)
        body = toks[1:a_pos]
        p = body.index(PLUS)
        da, db = body[:p], body[p + 1:]
        va = sum((x - DIG0) * 10 ** i for i, x in enumerate(da))
        vb = sum((x - DIG0) * 10 ** i for i, x in enumerate(db))
        return [DIG0 + x for x in _digits_le(va + vb, len(da) + 1)]
    if task == "state":
        a_pos = toks.index(A)
        return [DIG0 + sum(x - DIG0 for x in toks[1:a_pos]) % STATE_MOD]
    if task == "facts":
        key = toks[2:2 + FACT_KEY_LEN]
        for k, v in facts:
            if k == key:
                return v
        raise KeyError("fact key not in table")
    raise ValueError(task)


def answer_of(toks, mask):
    return [t for t, m in zip(toks, mask) if m]


# ------------------------------------------------------------------------------------------------ trivial baselines
def _shortcuts(task):
    """name -> fn(prompt tokens) -> answer tokens.  Cheap heuristics a model could pick up without doing the task."""
    if task == "mqar":
        def pairs(p):
            b = p[1:p.index(Q)]
            return [(b[i], b[i + 1]) for i in range(0, len(b), 2)]
        return {"first_value": lambda p: [pairs(p)[0][1]], "last_value": lambda p: [pairs(p)[-1][1]],
                "mode_value": lambda p: [Counter(v for _, v in pairs(p)).most_common(1)[0][0]]}
    if task == "hop":
        def edges(p):
            b = p[1:p.index(Q)]
            return {b[i]: b[i + 1] for i in range(0, len(b), 2)}
        return {"start": lambda p: [p[p.index(Q) + 1]],
                "succ_of_start": lambda p: [edges(p)[p[p.index(Q) + 1]]],
                "last_edge_target": lambda p: [p[p.index(Q) - 1]]}
    if task == "add":
        def nocarry(p):
            b = p[1:p.index(A)]
            i = b.index(PLUS)
            da, db = b[:i], b[i + 1:]
            return [DIG0 + ((x - DIG0) + (y - DIG0)) % 10 for x, y in zip(da, db)] + [DIG0]
        return {"digitwise_no_carry": nocarry}
    if task == "state":
        def body(p):
            return p[1:p.index(A)]
        return {"mode": lambda p: [Counter(body(p)).most_common(1)[0][0]], "last": lambda p: [body(p)[-1]],
                "first": lambda p: [body(p)[0]]}
    return {}


def baseline_table(split="test", n_per=500, facts=None, sets=None):
    """-> {(task,diff): dict(n, const, best_shortcut, best_shortcut_name, chance_analytic)}.
    const = accuracy of the single most common answer (measured on this very set: reveals answer-label imbalance)."""
    sets = sets if sets is not None else build_eval(split, n_per, facts)
    out = {}
    for (task, diff), items in sets.items():
        n = len(items)
        ans = [tuple(answer_of(t, m)) for t, m in items]
        const = Counter(ans).most_common(1)[0][1] / max(n, 1)
        best, bname = 0.0, None
        for name, fn in _shortcuts(task).items():
            hit = 0
            for (t, m), a in zip(items, ans):
                p = t[:len(t) - len(a)]
                hit += tuple(fn(p)) == a
            if hit / max(n, 1) > best:
                best, bname = hit / max(n, 1), name
        if task == "mqar":
            ch = 1.0 / min(N_VAL, diff)                  # best uninformed in-context guess: one of the n stored values
        elif task == "hop":
            ch = 1.0 / (N_HOP_NODES - 1)                 # answer is never the start node
        elif task == "add":
            ch = 10.0 ** -(diff + 1)
        elif task == "state":
            ch = 1.0 / STATE_MOD
        else:
            ch = 10.0 ** -FACT_VAL_LEN
        out[(task, diff)] = dict(n=n, const=const, best_shortcut=best, best_shortcut_name=bname, chance_analytic=ch,
                                 trivial=max(const, best, ch))
    return out


# ------------------------------------------------------------------------------------------------ model evaluation
def eval_sets(model, sets, device, amp=None, bs=128):
    """-> {"task|diff": dict(acc, lo, hi, tok_acc, n, ood)}.  Each (task,diff) group has equal-length instances."""
    import contextlib
    import torch
    was = model.training
    model.eval()
    res = {}
    with torch.no_grad():
        for (task, diff), items in sets.items():
            ok = tok_ok = tok_n = 0
            for i in range(0, len(items), bs):
                chunk = items[i:i + bs]
                assert len({len(t) for t, _ in chunk}) == 1, "instances in a group must have equal length"
                T = torch.tensor([t for t, _ in chunk], dtype=torch.long, device=device)
                Mk = torch.tensor([m for _, m in chunk], dtype=torch.bool, device=device)[:, 1:]
                x, y = T[:, :-1], T[:, 1:]
                with (amp() if amp is not None else contextlib.nullcontext()):
                    logits = model(x)[0]
                hit = logits.argmax(-1) == y
                ok += int((hit | ~Mk).all(1).sum())
                tok_ok += int((hit & Mk).sum())
                tok_n += int(Mk.sum())
            n = len(items)
            lo, hi = wilson(ok, n)
            res[f"{task}|{diff}"] = dict(acc=ok / max(n, 1), lo=lo, hi=hi, tok_acc=tok_ok / max(tok_n, 1), n=n,
                                         ood=is_ood(task, diff))
    model.train(was)
    return res


MIN_N = 30      # (task, difficulty) cells with fewer held-out instances are shown but excluded from summaries


def summarize(res, tasks=None, min_n=MIN_N):
    """per-task ID / OOD mean accuracy and 'frontier' (largest difficulty with acc >= 0.9 / >= 0.5, walking up from the
    easiest and stopping at the first miss).  Cells with n < min_n (tiny instance spaces) are ignored.
    res = eval_sets output."""
    out = {}
    for task in (tasks or TASKS):
        rows = sorted(((int(k.split("|")[1]), v) for k, v in res.items()
                       if k.split("|")[0] == task and v["n"] >= min_n), key=lambda r: r[0])
        if not rows:
            continue
        idv = [v["acc"] for d, v in rows if not v["ood"]]
        odv = [v["acc"] for d, v in rows if v["ood"]]
        fr = {}
        for thr in (0.9, 0.5):
            best = None
            for d, v in rows:
                if v["acc"] >= thr:
                    best = d
                else:
                    break
            fr[str(thr)] = best
        out[task] = dict(id=float(np.mean(idv)) if idv else None, ood=float(np.mean(odv)) if odv else None, frontier=fr)
    return out


# ------------------------------------------------------------------------------------------------ self test
def selftest(verbose=True):
    log = print if verbose else (lambda *a, **k: None)
    facts = make_fact_table(512)
    # 1. generator ground truth vs independent verifier, every task and difficulty
    rng = random.Random(1)
    n_checked = 0
    for task, spec in TASKS.items():
        for diff in sorted(set(spec["train"]) | set(spec["test"])):
            for _ in range(300):
                t, m, _b = make_instance(task, diff, rng, facts)
                assert len(t) == len(m) and m[0] == 0 and t[0] == BOS
                assert max(t) < VOCAB_MIN
                got = solve_from_tokens(task, t, facts)
                assert got == answer_of(t, m), (task, diff, t, got)
                ia = m.index(1)
                assert all(m[i] == 1 for i in range(ia, len(m))), "answer tokens must be the contiguous tail"
                n_checked += 1
    log(f"[ok] verifier agrees with generator on {n_checked} instances (all tasks/difficulties)")

    # 2. the longest instance fits the training context
    assert max_len() <= 256, max_len()
    log(f"[ok] longest instance {max_len()} tokens (<= seq 256)")

    # 3. splits: no train instance in a test/val bucket; test/val sets disjoint from each other and de-duplicated
    sets = {s: build_eval(s, 200, facts) for s in ("test", "val")}
    for s in sets:
        for (task, diff), items in sets[s].items():
            keys = [tuple(t) for t, _ in items]
            assert len(keys) == len(set(keys)), f"duplicates in {s} {task}|{diff}"
            if task != "facts":
                assert all(bucket(list(k)) == {"test": 0, "val": 1}[s] for k in keys)
    for key in sets["test"]:
        if key[0] != "facts":
            a = {tuple(t) for t, _ in sets["test"][key]}
            b = {tuple(t) for t, _ in sets["val"][key]}
            assert not (a & b), f"test/val overlap {key}"
    seen_buckets = Counter()
    for step in range(0, 400, 7):
        x, y, mk = make_batch(3, step, 8, 256, facts)
        for r in range(x.shape[0]):
            row = list(x[r]) + [int(y[r, -1])]
            starts = [i for i, t in enumerate(row) if t == BOS]
            for si, s0 in enumerate(starts):
                end = starts[si + 1] if si + 1 < len(starts) else len(row)
                inst = [t for t in row[s0:end] if t != PAD]
                if inst[1] == Q and inst[2] < DIG0 + 10 + 0 and False:
                    pass
                is_fact = len(inst) == 2 + FACT_KEY_LEN + 1 + FACT_VAL_LEN and inst[1] == Q and inst[2] >= LET0
                if not is_fact:
                    seen_buckets[bucket(inst)] += 1
    assert seen_buckets and seen_buckets[0] == 0 and seen_buckets[1] == 0, f"train stream hit held-out buckets {seen_buckets}"
    log(f"[ok] train stream: {sum(seen_buckets.values())} sampled instances, none in test/val buckets")

    # 4. packing: answers masked correctly, no fact key repeated inside a row, determinism, seeds differ
    x1, y1, m1 = make_batch(5, 11, 16, 256, facts)
    x2, y2, m2 = make_batch(5, 11, 16, 256, facts)
    assert (x1 == x2).all() and (m1 == m2).all(), "batch not a pure function of (seed, step)"
    x3, _, _ = make_batch(6, 11, 16, 256, facts)
    assert not (x1 == x3).all()
    for r in range(x1.shape[0]):
        row = list(x1[r])
        keys = [tuple(row[i + 2:i + 2 + FACT_KEY_LEN]) for i in range(len(row) - 5)
                if row[i] == BOS and row[i + 1] == Q and LET0 <= row[i + 2] < LET0 + 26]
        assert len(keys) == len(set(keys)), "fact key repeated inside a row"
    assert m1.sum() > 0 and (m1 * (y1 == PAD)).sum() == 0
    frac_pad = float((x1 == PAD).mean())
    log(f"[ok] batches deterministic; answer mask never on <pad>; pad fraction {frac_pad:.3f}; "
        f"answer tokens/row {m1.sum() / x1.shape[0]:.1f}")

    # 4b. every training difficulty is actually present in the stream, and no OOD difficulty is
    hop_ks, mqar_ns, add_ds, st_ns = set(), set(), set(), set()
    for step in range(0, 300, 3):
        x, y, mk = make_batch(9, step, 8, 256, facts)
        for r in range(x.shape[0]):
            row = list(x[r])
            for i, tkn in enumerate(row):
                if tkn == BOS and i + 1 < len(row):
                    j = i + 1
                    end = row.index(BOS, j) if BOS in row[j:] else len(row)
                    inst = [t for t in row[i:end] if t != PAD]
                    if Q in inst and HOP in inst:
                        hop_ks.add(inst.count(HOP))
                    elif Q in inst and inst[1] >= KEY0 and inst[1] < KEY0 + N_KEY:
                        mqar_ns.add((inst.index(Q) - 1) // 2)
                    elif PLUS in inst:
                        add_ds.add((inst.index(A) - 2) // 2)
                    elif A in inst and Q not in inst and inst[1] < DIG0 + 10:
                        st_ns.add(inst.index(A) - 1)
    assert hop_ks == set(TASKS["hop"]["train"]), hop_ks
    assert mqar_ns == set(TASKS["mqar"]["train"]), mqar_ns
    assert add_ds == set(TASKS["add"]["train"]), add_ds
    assert st_ns == set(TASKS["state"]["train"]), st_ns
    log("[ok] training stream contains exactly the declared training difficulties (no OOD leakage)")

    # 5. trivial baselines: nothing beats chance by much (no answer imbalance / cheap shortcuts)
    bt = baseline_table(sets=sets["test"], facts=facts)
    worst = []
    for (task, diff), v in bt.items():
        if task in ("mqar", "hop", "state") and v["n"] >= 100:
            worst.append((v["trivial"] - v["chance_analytic"], task, diff, v["const"], v["best_shortcut"], v["best_shortcut_name"]))
    worst.sort(reverse=True)
    log("   largest (trivial - analytic chance) among n>=100 groups (small n => noise ~ +-0.05):")
    for w in worst[:4]:
        log(f"     {w[1]}|{w[2]}: const {w[3]:.3f} shortcut {w[4]:.3f} ({w[5]})")
    # the only place a shortcut is *supposed* to work is hop with k=1 (successor of start) -- and it must be exact there
    assert abs(bt[("hop", 1)]["best_shortcut"] - 1.0) < 1e-9 and bt[("hop", 1)]["best_shortcut_name"] == "succ_of_start"
    for diff in (2, 3, 4, 5, 6, 7, 8, 10):
        assert bt[("hop", diff)]["trivial"] < 0.25, bt[("hop", diff)]
    for diff in TASKS["state"]["test"]:
        if bt[("state", diff)]["n"] >= 100:
            assert bt[("state", diff)]["trivial"] < 0.45, bt[("state", diff)]
    log("[ok] trivial baselines low (hop k=1 is solvable by lookup, by construction)")
    log("SELFTEST PASSED")
    return True


